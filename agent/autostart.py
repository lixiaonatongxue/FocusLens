"""开机自动采集：在当前用户 Startup 文件夹放一个 .vbs 启动器。

设计取向：
- 不写注册表、不装服务、不需要管理员权限；
- 卸载 = 删一个文件（`python run.py autostart --remove`）；
- 登录时以 pythonw 无窗口运行 `run.py collect --quiet`；
- data/collector.pid 用于单实例保护与停止；data/collector.log 记录输出。
"""

from __future__ import annotations

import ctypes
import os
import subprocess
import sys
import time
from pathlib import Path
from typing import Optional

SYNCHRONIZE = 0x00100000
WAIT_TIMEOUT = 0x102
PROCESS_TERMINATE = 0x0001

PID_FILENAME = "collector.pid"
LAUNCHER_NAME = "focuslens-collector.vbs"

_VBS_TEMPLATE = (
    "' FocusLens collector auto-start (generated by `run.py autostart`)\n"
    "' Delete this file, or run `python run.py autostart --remove`, to uninstall.\n"
    "Set sh = CreateObject(\"WScript.Shell\")\n"
    "q = Chr(34)\n"
    "sh.CurrentDirectory = \"{root}\"\n"
    "sh.Run q & \"{pythonw}\" & q & \" \" & q & \"{runpy}\" & q & \" collect --quiet\", 0, False\n"
)


def _kernel32():
    return ctypes.windll.kernel32


def pid_alive(pid: Optional[int]) -> bool:
    if not pid or pid <= 0:
        return False
    try:
        k32 = _kernel32()
        handle = k32.OpenProcess(SYNCHRONIZE, False, int(pid))
    except Exception:  # 非 Windows 或意外错误，按不存活处理
        return False
    if not handle:
        return False
    try:
        return k32.WaitForSingleObject(handle, 0) == WAIT_TIMEOUT
    finally:
        k32.CloseHandle(handle)


# -- 启动器文件 -----------------------------------------------------------


def default_startup_dir() -> Path:
    return (
        Path(os.environ["APPDATA"])
        / "Microsoft"
        / "Windows"
        / "Start Menu"
        / "Programs"
        / "Startup"
    )


def launcher_path(startup_dir: Optional[Path] = None) -> Path:
    return (startup_dir or default_startup_dir()) / LAUNCHER_NAME


def pythonw_path() -> Path:
    candidate = Path(sys.executable).with_name("pythonw.exe")
    return candidate if candidate.exists() else Path(sys.executable)


def install(root: Path, startup_dir: Optional[Path] = None) -> Path:
    """生成（或覆盖）启动器 .vbs，返回其路径。"""
    root = Path(root)
    target = launcher_path(startup_dir)
    target.parent.mkdir(parents=True, exist_ok=True)
    content = _VBS_TEMPLATE.format(
        root=root, pythonw=pythonw_path(), runpy=root / "run.py"
    )
    try:
        target.write_text(content, encoding="ascii")
    except UnicodeEncodeError:
        # 路径含中文等字符时用 UTF-16（WSH 原生支持）
        target.write_bytes(b"\xff\xfe" + content.encode("utf-16-le"))
    return target


def uninstall(startup_dir: Optional[Path] = None) -> bool:
    target = launcher_path(startup_dir)
    if target.exists():
        target.unlink()
        return True
    return False


# -- 采集进程管理 ---------------------------------------------------------


def pid_file(data_dir: Path) -> Path:
    return Path(data_dir) / PID_FILENAME


def read_pid(data_dir: Path) -> Optional[int]:
    try:
        return int(pid_file(data_dir).read_text(encoding="utf-8").strip())
    except (OSError, ValueError):
        return None


def write_pid(data_dir: Path, pid: int) -> None:
    data_dir = Path(data_dir)
    data_dir.mkdir(parents=True, exist_ok=True)
    pid_file(data_dir).write_text(str(pid), encoding="utf-8")


def clear_pid(data_dir: Path) -> None:
    try:
        pid_file(data_dir).unlink()
    except OSError:
        pass


def collector_running(data_dir: Path) -> Optional[int]:
    """返回正在运行的采集器 PID；未运行返回 None。"""
    pid = read_pid(data_dir)
    return pid if pid_alive(pid) else None


def stop_collector(data_dir: Path) -> bool:
    """结束后台采集器（会丢掉尚未落盘的当前段，最多 60 秒）。"""
    pid = read_pid(data_dir)
    if not pid_alive(pid):
        clear_pid(data_dir)
        return False
    k32 = _kernel32()
    handle = k32.OpenProcess(PROCESS_TERMINATE, False, pid)
    if handle:
        try:
            k32.TerminateProcess(handle, 1)
        finally:
            k32.CloseHandle(handle)
    for _ in range(30):
        if not pid_alive(pid):
            break
        time.sleep(0.1)
    clear_pid(data_dir)
    return True


def launch_collector_now(root: Path, data_dir: Path) -> int:
    """立即无窗口启动采集（不等下次登录）。返回新进程 PID。"""
    data_dir = Path(data_dir)
    data_dir.mkdir(parents=True, exist_ok=True)
    log = open(data_dir / "collector.log", "ab")
    try:
        proc = subprocess.Popen(
            [str(pythonw_path()), str(Path(root) / "run.py"), "collect", "--quiet"],
            cwd=str(root),
            stdout=log,
            stderr=subprocess.STDOUT,
            stdin=subprocess.DEVNULL,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    finally:
        log.close()
    return proc.pid
